def pixel_export(im,size,margin=2):
 im=im.convert('RGBA'); alpha=im.getchannel('A').point(lambda a:255 if a>=150 else 0)
 # Remove isolated generation specks before fitting, preserving intentional multi-piece sprites.
 points={(x,y) for y in range(im.height) for x in range(im.width) if alpha.getpixel((x,y))}
 components=[]
 while points:
  start=points.pop(); stack=[start]; component=[start]
  while stack:
   x,y=stack.pop()
   for q in ((x-1,y),(x+1,y),(x,y-1),(x,y+1)):
    if q in points:points.remove(q);stack.append(q);component.append(q)
  components.append(component)
 minimum=max(10,max((len(c) for c in components),default=0)*.002)
 for component in components:
  if len(component)<minimum:
   for q in component:alpha.putpixel(q,0)
 im.putalpha(alpha); bbox=alpha.getbbox()
 if not bbox: raise ValueError('empty generated sprite')
 im=im.crop(bbox); maxw,maxh=size[0]-margin*2,size[1]-margin*2
 scale=min(maxw/im.width,maxh/im.height)
 im=im.resize((max(1,round(im.width*scale)),max(1,round(im.height*scale))),NN)
 a=im.getchannel('A'); rgb=im.convert('RGB').quantize(palette=palette,dither=Image.Dither.NONE).convert('RGBA');rgb.putalpha(a)
 out=Image.new('RGBA',size); out.alpha_composite(rgb,((size[0]-im.width)//2,(size[1]-im.height)//2))
 # Canonical zero RGB under transparent pixels.
 out.putdata([p if p[3] else (0,0,0,0) for p in out.getdata()])
 return out

