# Periodic boundary correction on generated textures; no procedural art replacement.
def periodic(im,axes='xy',band=7):
 im=im.copy().convert('RGBA'); w,h=im.size; src=im.copy()
 if 'x' in axes:
  for y in range(h):
   for k in range(band):
    a,b=src.getpixel((k,y)),src.getpixel((w-1-k,y)); t=(1-k/band)*.5
    im.putpixel((k,y),tuple(round(a[j]*(1-t)+b[j]*t) for j in range(4)))
    im.putpixel((w-1-k,y),tuple(round(b[j]*(1-t)+a[j]*t) for j in range(4)))
 if 'y' in axes:
  src=im.copy()
  for x in range(w):
   for k in range(band):
    a,b=src.getpixel((x,k)),src.getpixel((x,h-1-k));t=(1-k/band)*.5
    im.putpixel((x,k),tuple(round(a[j]*(1-t)+b[j]*t) for j in range(4)))
    im.putpixel((x,h-1-k),tuple(round(b[j]*(1-t)+a[j]*t) for j in range(4)))
 return im

